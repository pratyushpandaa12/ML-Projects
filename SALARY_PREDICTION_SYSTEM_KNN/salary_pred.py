#pairplot

import seaborn as sns
import matplotlib.pyplot as plt

sns.pairplot(dataset,hue="education.num")
plt.show()

dataset.describe()

"""**SEGRIGATING THE X AXIS VALUE AND Y AXIS VALUE**"""

X = dataset.iloc[:, :-1].values
X

Y = dataset.iloc[:, -1].values
Y

"""**SPLITTING THE DATA IN TO TRAINING AND TESTING DATA**"""

from sklearn.model_selection import train_test_split
X_train, X_test, y_train, y_test = train_test_split(X, Y, test_size = 0.25, random_state = 0)

from sklearn.preprocessing import StandardScaler
sc = StandardScaler()
X_train = sc.fit_transform(X_train)
X_test = sc.transform(X_test)

"""**GETTING THE VALUE FOR WHICH THE ERROR WILL BE LESS**"""

error = []
from sklearn.neighbors import KNeighborsClassifier
import matplotlib.pyplot as plt

# Calculating error for K values between 1 and 40
for i in range(1, 40):
    model = KNeighborsClassifier(n_neighbors=i)
    model.fit(X_train, y_train)
    pred_i = model.predict(X_test)
    error.append(np.mean(pred_i != y_test))

plt.figure(figsize=(12, 6))
plt.plot(range(1, 40), error, color='red', linestyle='dashed', marker='o',
         markerfacecolor='blue', markersize=10)
plt.title('Error Rate K Value')
plt.xlabel('K Value')
plt.ylabel('Mean Error')

"""**FROM THE ABOVE PLOT WE CAN SEE THAT FOR K VALUE 30WE GETTING THE LEAST ERROR**"""

from sklearn.neighbors import KNeighborsClassifier
model = KNeighborsClassifier(n_neighbors = 30, metric = 'minkowski', p = 2)
model.fit(X_train, y_train)

